/* 翻訳エンジンのテスト: node tests/translator.test.js で実行 */
const { translate } = require("../js/translator.js");

const cases = [
  // [入力, 期待される出力]
  ["昨日、友達と牛乳を飲んだ。", "昨日、ドルーグとモロコをピートした。"],
  ["友達を見る", "ドルーグをビディーする"],
  ["彼の頭を殴った", "彼のガリバーをトルチョックした"],
  ["良い天気ですね", "ホラーショーな天気ですね"],
  ["すごくよかった", "ホラーショーにホラーショーだった"],
  ["少女が叫んで、警官が走ってきた", "デボチカがクリーチして、ミリセントが走ってきた"],
  ["お金がない", "デングがない"],
  ["昨夜は眠れなかった", "昨夜は眠れなかった"], // 可能形は未対応: そのまま
  ["音楽を聞きました", "音楽をスルーシーしました"], // 音楽はブロック、聞くは変換
  ["電話で話した", "電話でゴボリートした"],
  ["買い物に行く", "買い物にイッティーする"],
  ["目が見えない", "グラズが見えない"],
  ["駄目な目", "駄目なグラズ"],
  ["ミルクバーでミルクを飲もう", "モロコバーでモロコをピートしよう"], // コロヴァ・ミルクバー=モロコバー
  ["夜の街を歩く", "ノーチーの街をグーリーする"],
  ["古い家", "スターリーなドミー"],
  ["家族と家にいる", "家族とドミーにいる"],
  ["小さい男の子が泣いています", "マレンキーなマルチックがプラッチしています"],
  ["言葉がわからない", "スロヴォがポニーしない"],
  ["手紙を手で書く", "手紙をルーカーで書く"],
];

let pass = 0;
let fail = 0;
for (const [input, expected] of cases) {
  const actual = translate(input);
  if (actual === expected) {
    pass++;
    console.log(`  OK: ${input} → ${actual}`);
  } else {
    fail++;
    console.log(`FAIL: ${input}`);
    console.log(`      期待: ${expected}`);
    console.log(`      実際: ${actual}`);
  }
}
console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
